// Exports every 360-document exhibit as a GLB for <model-viewer>: makeDocumentMesh (the same paper
// box the room uses) textured with the holder's scan pages (site/public/media/<key>.jpg from
// tools/fetch_media.py: front, and back when the exhibit names one), written by three's
// GLTFExporter to site/public/media/<model key>.glb. GLTFExporter encodes images through a canvas,
// so the export runs in headless Chromium (Playwright) with files served from disk. GLBs no
// exhibit uses are removed. Writes site/public/media/MODELS.md (what each GLB was built from).
// Usage (from site/): node scripts/export-docs.mjs
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync, readdirSync, existsSync, unlinkSync } from 'node:fs';
import { join, resolve, extname } from 'node:path';
import { exhibitFiles } from '../src/museum/mediafiles.js';
import { jpegSize, listChapters, loadChapter } from '../src/content/load.js';

const SITE = resolve(process.cwd());
const MEDIA = join(SITE, 'public', 'media');
const PAPER_HEIGHT = 0.279; // m; width follows the front scan's aspect

const jobs = new Map();
for (const { slug, n } of listChapters()) {
  for (const ex of loadChapter(slug, n).exhibits || []) {
    if (ex.type !== '360-document') continue;
    const f = exhibitFiles(ex);
    const front = join(MEDIA, `${f.front}.jpg`);
    if (!existsSync(front)) throw new Error(`${slug}/${n} ${ex.id}: missing ${front} (run tools/fetch_media.py)`);
    if (f.back && !existsSync(join(MEDIA, `${f.back}.jpg`))) throw new Error(`${slug}/${n} ${ex.id}: missing back page ${f.back}.jpg`);
    const size = jpegSize(readFileSync(front));
    jobs.set(f.model, { model: f.model, mediaId: ex.media_id, pages: ex.pages || [], front: f.front, back: f.back, height: PAPER_HEIGHT, width: +(PAPER_HEIGHT * size.width / size.height).toFixed(4), where: `${slug}/${n} ${ex.id}` });
  }
}

// "EIN-M-0019 pages 3 and 4" / "EIN-M-0015 page 1" (from the exhibit's media id and pages).
function pagesText(j) {
  return j.pages.length ? `${j.mediaId} ${j.pages.length > 1 ? `pages ${j.pages.join(' and ')}` : `page ${j.pages[0]}`}` : `${j.mediaId} (one image)`;
}

const TYPES = { '.js': 'text/javascript', '.jpg': 'image/jpeg', '.html': 'text/html' };
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  await page.route('http://voa.local/**', route => {
    const path = new URL(route.request().url()).pathname;
    if (path === '/') {
      return route.fulfill({ contentType: 'text/html', body: `<!doctype html><script type="importmap">${JSON.stringify({ imports: {
        three: '/node_modules/three/build/three.module.js', 'three/addons/': '/node_modules/three/examples/jsm/' } })}</script>` });
    }
    const file = join(SITE, decodeURIComponent(path));
    if (!file.startsWith(SITE) || !existsSync(file)) return route.fulfill({ status: 404, body: '' });
    return route.fulfill({ contentType: TYPES[extname(file)] || 'application/octet-stream', body: readFileSync(file) });
  });
  await page.goto('http://voa.local/');
  for (const job of jobs.values()) {
    const b64 = await page.evaluate(async j => {
      const THREE = await import('three');
      const { GLTFExporter } = await import('three/addons/exporters/GLTFExporter.js');
      const { makeDocumentMesh } = await import('/src/museum/docmesh.js');
      const load = async key => {
        if (!key) return null;
        const t = await new THREE.TextureLoader().loadAsync(`/public/media/${key}.jpg`);
        t.colorSpace = THREE.SRGBColorSpace; t.userData.mimeType = 'image/jpeg';
        return t;
      };
      const mesh = makeDocumentMesh(THREE, { width: j.width, height: j.height, frontTexture: await load(j.front), backTexture: await load(j.back) });
      mesh.name = j.model;
      const glb = await new GLTFExporter().parseAsync(mesh, { binary: true });
      let s = ''; const u = new Uint8Array(glb);
      for (let i = 0; i < u.length; i += 0x8000) s += String.fromCharCode(...u.subarray(i, i + 0x8000));
      return btoa(s);
    }, job);
    const buf = Buffer.from(b64, 'base64');
    writeFileSync(join(MEDIA, `${job.model}.glb`), buf);
    console.log(`${job.model}.glb ${buf.length} B (${job.where}: ${pagesText(job)}, ${job.width} x ${job.height} m)`);
  }
} finally {
  await browser.close();
}
for (const f of readdirSync(MEDIA)) {
  if (f.endsWith('.glb') && !jobs.has(f.slice(0, -4))) { unlinkSync(join(MEDIA, f)); console.log(`removed unused ${f}`); }
}
writeFileSync(join(MEDIA, 'MODELS.md'), ['# 360 document models', '',
  'Generated by `site/scripts/export-docs.mjs`. Each GLB is our reconstruction: a 1.5 mm paper box (makeDocumentMesh)',
  'textured with the holder\'s scan pages listed here (credits for the pages are in CREDITS.md): the first page on the',
  'front face, the second (if any) on the back face. Putting two pages on one sheet is our presentation; it does not',
  'state how the original pages are bound or printed. A model with one page has a plain paper back.', '',
  '| Model | Exhibit | Scan pages | Size (m) |', '|---|---|---|---|',
  ...[...jobs.values()].map(j => `| ${j.model}.glb | ${j.where} | ${pagesText(j)} | ${j.width} x ${j.height} |`), ''].join('\n'));
