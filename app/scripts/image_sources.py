"""The source of every standalone image the site ships (app/public, outside the glbs), with hashes:
assets-src/app-public/images.json, { "<public path>": entry }, entry =
  sha256         the shipped file
  source         {"media": id} (a cleared record), {"thirdParty": name} (a library its declaration
                 lists), or {"derivedFrom": "<public path>"} (made from another shipped image)
  sourceFile     the file it was made from (repo path), and sourceSha256 its hash when recorded
  transform      how (the script that made it, or the command)
  generator      for a generated image (a photo room's plate or mask): {script, sha256} of the script

  proof          what the record proves about the step from source to image:
                 "identical"  the image is a byte copy of its source file (sha256 == sourceSha256); the
                              gate checks this every build, so the step is verified, not only pinned
                 "pinned"     a resize, crop, re-encode or generated plate: the record pins both ends
                              (image and source hashes, and the generator script's) but nothing here
                              re-runs the step, so it does not prove the image was made from the source

`--record` writes images.json and refuses (exit 1) to record an image whose source it cannot resolve
to a declared source file (it never sets a baseline for an undeclared image). It also refuses a
re-baseline: when an image already recorded would get other hashes, another source, transform or
generator, or would be dropped, it writes nothing unless run with `--rebaseline --reason "<why>"`;
every write is appended to assets-src/app-public/record-log.jsonl (date, tool, reason, each change
with its old and new hashes). check() (run by check_textures.py) fails when an image has no entry, its
bytes differ, its source file (when present in this checkout) differs from the recorded hash, an
"identical" image is not its source's bytes, its generator script changed, or a derived image's
parent changed.
"""
