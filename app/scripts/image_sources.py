def media_script_jobs():
    """{public path: (source file, script)} from the record folders' make_media.py job tables."""
    out = {}
    roots = {"SITE": "site/public/media", "ASSETS": "assets-src"}
    for script in sorted(REPO.glob("assets-src/*/make_media.py")):
        here = script.parent.relative_to(REPO).as_posix()
        slug = script.parent.name.split("-")[0]
        for m in re.finditer(r'\((SITE|HERE|ASSETS)((?:\s*/\s*"[^"]+")+),\s*"([A-Z]{3}-M-\d{4}(?:-p\d+)?)",\s*\d+,\s*(?:"([A-Z]{3}-M-\d{4})"|None)\)', script.read_text()):
            base = roots.get(m.group(1), here)
            src = "/".join([base, *re.findall(r'"([^"]+)"', m.group(2))])
            rel = script.relative_to(REPO).as_posix()
            out[f"media/{slug}/{m.group(3)}.webp"] = (src, rel)
            if m.group(4):
                out[f"landing/artifacts/{m.group(4)}.webp"] = (src, f"{rel} (480 px thumbnail)")
    return out


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def shipped_images():
    return sorted(p.relative_to(PUBLIC).as_posix() for p in PUBLIC.rglob("*") if p.is_file() and IMAGE.search(p.name))


def _credits_source(rel):
    """The source file app/CREDITS.md names for a shipped file (its row), if any."""
    text = (REPO / "app/CREDITS.md").read_text(encoding="utf-8")
    for line in text.splitlines():
        if line.startswith("| ") and f"public/{rel}" in line:
            m = re.search(r"((?:assets-src|site/public)/[^\s,;()`]+\.(?:jpe?g|tiff?|png|jp2|webp))", line)
            if m and (REPO / m.group(1)).exists():
                return m.group(1)
    return None


def _ref_source(base):
    """A holder download kept in a source folder: site/public/media/<base>.jpg or assets-src/*/ref/<base>.*"""
    for cand in [SITE_MEDIA / f"{base}.jpg", *sorted(REPO.glob(f"assets-src/*/ref/{base}.*"))]:
        if cand.exists() and cand.suffix.lower() in (".jpg", ".jpeg", ".tif", ".tiff", ".png", ".jp2"):
            return cand.relative_to(REPO).as_posix()
    return None


def resolve(rel):
    """The entry for one shipped image, or None when its source cannot be resolved."""
    name = Path(rel).name
    tex = re.match(r"tour/tex/(walnut|planks|plaster)-", rel)
    if rel in COPIES:
        src, f, how = COPIES[rel]
        return {"source": src, "sourceFile": f, "transform": how}
    if rel in PORTRAITS:
        mid, f = PORTRAITS[rel]
        return {"source": {"media": mid}, "sourceFile": f, "transform": f"{PORTRAIT_SCRIPT} (4:5 crop, long side <= 1024 px)",
                "generator": {"script": PORTRAIT_SCRIPT, "sha256": sha(REPO / PORTRAIT_SCRIPT)}}
    if tex:
        kind = "normal" if "normal" in name else "color"
        files = sorted((REPO / "site/public/tex" / tex.group(1)).glob(f"{kind}-*.webp"))
        mine = sha(PUBLIC / rel)
        f = next((x for x in files if sha(x) == mine), None)  # copied unchanged
        if f:
            return {"source": {"thirdParty": "Poly Haven (CC0)"}, "sourceFile": f.relative_to(REPO).as_posix(), "transform": "copied from the v1 site (site/public/tex/CREDITS.md)"}
        return None
    for prefix, (mid, f, script) in PHOTO_ROOMS.items():
        if rel.startswith(prefix + "-"):
            part = rel[len(prefix) + 1:].split(".")[0]
            entry = {"source": {"media": mid}, "sourceFile": f, "transform": f"{script} ({part})",
                     "generator": {"script": script, "sha256": sha(REPO / script)}}
            return entry
    if rel in RECORD_FILES:
        f, how = RECORD_FILES[rel]
        return {"source": {"media": MEDIA_ID.search(name).group(0)}, "sourceFile": f, "transform": how}
    jobs = media_script_jobs()
    if rel in jobs:
        f, how = jobs[rel]
        return {"source": {"media": MEDIA_ID.search(name).group(0)}, "sourceFile": f, "transform": how}
    mid = MEDIA_ID.search(name)
    if not mid:
        return None
    base = name.rsplit(".", 1)[0]
    if rel.startswith("landing/artifacts/"):
        sys.path.insert(0, str(REPO / "app/src/landing/data"))
        import build_inductees  # noqa: E402  the landing's own thumbnail source rule
        src = build_inductees.thumb_source(mid.group(0))
        if src is None:
            return None
        return {"source": {"media": mid.group(0)}, "sourceFile": Path(src).resolve().relative_to(REPO).as_posix(), "transform": "app/src/landing/data/build_inductees.py thumb (480 px, WebP q82)"}
    f = _ref_source(base) or _credits_source(rel)
    if not f:
        return None
    return {"source": {"media": mid.group(0)}, "sourceFile": f, "transform": "resized and re-encoded to WebP (the record folder's media script, app/CREDITS.md)"}


class Refused(Exception):
    pass


def baseline_changes(old, new, keys=None):
    """{path: {"old": entry, "new": entry}} for every recorded entry `new` would change or drop (an
    added path is not a re-baseline)"""
    out = {}
    for k, o in old.items():
        n = new.get(k)
        pick = (lambda e: {f: e.get(f) for f in keys}) if keys else (lambda e: e)
        if n is None or pick(o) != pick(n):
            out[k] = {"old": o, "new": n}
    return out


def guard_rebaseline(tool, target, old, new, rebaseline=False, reason=None, log=RECORD_LOG, keys=None):
    """Raise Refused for a re-baseline without --rebaseline and a reason; otherwise append the write
    (with every change, old and new) to the record log."""
    changes = baseline_changes(old, new, keys)
    reason = (reason or "").strip()
    if changes and not (rebaseline and reason):
        raise Refused(f"{target}: a re-baseline of {len(changes)} recorded item(s) ({', '.join(sorted(changes)[:5])}"
                      f"{', ...' if len(changes) > 5 else ''}); run again with --rebaseline --reason \"<why>\" if this is intended")
    added = sorted(set(new) - set(old))
    if changes or added:
        Path(log).parent.mkdir(parents=True, exist_ok=True)
        entry = {"date": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"), "tool": tool, "target": str(target),
                 "reason": reason or "first record of new items", "added": added, "changed": changes}
        with open(log, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    return changes


def record(rebaseline=False, reason=None):
    out, missing = {}, []
    for rel in shipped_images():
        e = resolve(rel)
        if e is None:
            missing.append(rel)
            continue
        src = REPO / e["sourceFile"]
        if not src.exists():
            missing.append(f"{rel} (source file {e['sourceFile']} not in this checkout)")
            continue
        h, hs = sha(PUBLIC / rel), sha(src)
        out[rel] = {"sha256": h, **e, "sourceSha256": hs, "proof": "identical" if h == hs else "pinned"}
    if missing:
        print("refused: no declared source file for\n  " + "\n  ".join(missing), file=sys.stderr)
        return 1
    old = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else {}
    # adding the proof field to an entry is not a re-baseline; any other difference is
    strip = lambda d: {k: {f: v for f, v in e.items() if f != "proof"} for k, e in d.items()}  # noqa: E731
    try:
        guard_rebaseline("image_sources.py --record", MANIFEST.relative_to(REPO), strip(old), strip(out), rebaseline, reason)
    except Refused as e:
        print(f"refused: {e}", file=sys.stderr)
        return 1
    MANIFEST.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"recorded {len(out)} images in {MANIFEST.relative_to(REPO)}")
    return 0


def check(repo=REPO, manifest=None, index=None):
    repo = Path(repo)
    public = repo / "app/public"
    path = Path(manifest) if manifest else repo / "assets-src/app-public/images.json"
    entries = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    media = (index or {}).get("media", {})
    errs = []
    images = sorted(p.relative_to(public).as_posix() for p in public.rglob("*") if p.is_file() and IMAGE.search(p.name))
    for rel in images:
        e = entries.get(rel)
        if not e:
            errs.append(f"{rel}: no recorded source (assets-src/app-public/images.json; image_sources.py --record)")
            continue
        if sha(public / rel) != e.get("sha256"):
            errs.append(f"{rel}: its bytes differ from the recorded image")
        if e.get("proof") not in ("identical", "pinned"):
            errs.append(f"{rel}: no proof class (identical or pinned; image_sources.py --record)")
        elif e["proof"] == "identical" and e.get("sha256") != e.get("sourceSha256"):
            errs.append(f"{rel}: recorded as a byte copy of {e.get('sourceFile')} but its hash is not the source's")
        src = e.get("source") or {}
        if "media" in src:
            if index is not None and not media.get(src["media"], {}).get("embeddable"):
                errs.append(f"{rel}: its source {src['media']} is not a verified, cleared record")
            named = MEDIA_ID.search(Path(rel).name)
            if named and named.group(0) != src["media"]:
                errs.append(f"{rel}: named for {named.group(0)} but recorded from {src['media']}")
        elif "thirdParty" not in src:
            errs.append(f"{rel}: no declared source (media record or third-party library)")
        if not re.fullmatch(r"[0-9a-f]{64}", e.get("sourceSha256") or ""):
            errs.append(f"{rel}: no source-file hash")
        sf = repo / (e.get("sourceFile") or "")
        if e.get("sourceFile") and sf.is_file() and sha(sf) != e.get("sourceSha256"):
            errs.append(f"{rel}: its source file {e['sourceFile']} differs from the recorded hash")
        gen = e.get("generator")
        if gen and (repo / gen["script"]).is_file() and sha(repo / gen["script"]) != gen["sha256"]:
            errs.append(f"{rel}: its generator {gen['script']} changed since the image was recorded; run it and record again")
    for rel in entries:
        if rel not in images:
            errs.append(f"{rel}: recorded but not shipped (record again)")
    return errs


def rebaseline_args(argv):
    """(--rebaseline given, the --reason text)"""
    reason = argv[argv.index("--reason") + 1] if "--reason" in argv and argv.index("--reason") + 1 < len(argv) else None
    return "--rebaseline" in argv, reason


if __name__ == "__main__":
    if "--record" in sys.argv[1:]:
        sys.exit(record(*rebaseline_args(sys.argv[1:])))
    idx = json.loads((REPO / "app/src/tour/data/facts.generated.json").read_text())
    errs = check(index=idx)
    for e in errs:
        print(e, file=sys.stderr)
    sys.exit(1 if errs else 0)
