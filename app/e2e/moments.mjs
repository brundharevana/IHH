// "Moments That Made Them" layout check (ported from the old index check): the header, the filter
// chips and the moment cards never overlap each other and no card leaves the screen, at 1440x900,
// 1280x720 and 390x844, in the scattered view, after Shuffle (three seeds), in Timeline view and with
// a kind filter on. Also: no link-only media renders an image, a moment links to its chapter
// (tour.html?inductee=&chapter=), the old ?view=constellations URL lands on this page, the phone has
// no horizontal scroll. Exit 1 on any failure.
// Needs the dev server (npm run dev, http://localhost:5173).
// usage: node e2e/moments.mjs [--shots]   --shots writes screenshots to mockup-shots/task8/ (default
// off; nothing is written without it)
import { existsSync, mkdirSync, readFileSync } from 'node:fs'
import { chromium } from './browser.mjs' // Playwright: $SITE_MODULES or ../Challenge IHH/site (browser.mjs)

const BASE = process.env.BASE || 'http://localhost:5173'
const shots = process.argv.includes('--shots')
const shotDir = new URL('../mockup-shots/task8/', import.meta.url).pathname
if (shots) mkdirSync(shotDir, { recursive: true })
const SHELL = `${process.env.HOME}/Library/Caches/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-mac-arm64/chrome-headless-shell`
const VIEWS = [['desktop', 1440, 900], ['laptop', 1280, 720], ['phone', 390, 844]]
const LINK_ONLY = ['NAI-M-0004', 'EIN-M-0016', 'EIN-M-0058', 'EIN-M-0049', 'MUI-M-0061', 'LAM-M-0028']
// the Moments thumbnails records.lock.json declares (src/tour/data/shownRecords.js): moments/<slug>/<chapter>:<media | none>
const MOMENT_LOCK = JSON.parse(readFileSync(new URL('../src/tour/data/records.lock.json', import.meta.url), 'utf8')).records.filter((r) => r.startsWith('moments/'))
// the chapters that may show the kind icon (hand-written, with reasons; round 9 fix round 7): the lock is regenerated by
// script, so a `none` in it alone does not make the icon acceptable
const { NO_THUMB } = await import('../src/tour/moments/noThumb.js')
const hit = (a, b) => a.left < b.right && b.left < a.right && a.top < b.bottom && b.top < a.bottom

const browser = await chromium.launch({ ...(existsSync(SHELL) ? { executablePath: SHELL } : {}), args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] })
let bad = 0
const fail = (m) => {
  bad++
  console.log(`  FAIL ${m}`)
}

for (const [name, w, h] of VIEWS) {
  const page = await browser.newPage({ viewport: { width: w, height: h }, ...(name === 'phone' ? { isMobile: true, hasTouch: true } : {}) })
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  await page.goto(`${BASE}/tour.html?view=moments`, { waitUntil: 'networkidle' })
  // the page never drew its cards (a thumbnail that names a record with no image throws in dev): fail with its errors
  if (!(await page.waitForSelector('.mom-float').then(() => true, () => false))) {
    fail(`${name}: no moment cards drawn: ${errors.slice(0, 3).join(' | ') || 'no error reported'}`)
    await page.close()
    continue
  }
  await page.evaluate(() => document.querySelectorAll('img').forEach((i) => (i.loading = 'eager')))
  // round 9 fix round 6 (Codex review 5): every card shows the thumbnail records.lock.json declares for its chapter,
  // its own image loaded (or, only where the lock says `none`, the kind icon); a card that lost its image fails
  await page.evaluate(() => Promise.all([...document.images].map((i) => i.decode().catch(() => {}))))
  const thumbs = await page.evaluate(() =>
    [...document.querySelectorAll('.mom-float')].map((e) => {
      const q = new URLSearchParams((e.querySelector('a')?.getAttribute('href') || '').split('?')[1] || '')
      const t = e.querySelector('[data-thumb]')
      const img = t?.querySelector('img')
      return { key: `${q.get('inductee')}/${q.get('chapter')}`, thumb: t?.getAttribute('data-thumb') || null, loaded: Boolean(img && img.complete && img.naturalWidth > 0), src: img?.getAttribute('src') || null }
    }),
  )
  const want = Object.fromEntries(MOMENT_LOCK.map((r) => r.slice('moments/'.length).split(':')))
  if (thumbs.length !== Object.keys(want).length) fail(`${name}: ${thumbs.length} moment cards, ${Object.keys(want).length} declared`)
  for (const t of thumbs) {
    if (!(t.key in want)) fail(`${name}: the moment ${t.key} is not declared`)
    else if (t.thumb !== want[t.key]) fail(`${name}: the moment ${t.key} shows thumbnail ${t.thumb}, declared ${want[t.key]}`)
    else if (t.thumb !== 'none' && !t.loaded) fail(`${name}: the moment ${t.key} thumbnail ${t.thumb} (${t.src}) did not load`)
    if (t.thumb === 'none' && !NO_THUMB[t.key]) fail(`${name}: the moment ${t.key} shows the kind icon but is not in noThumb.js`)
  }
  console.log(name, `thumbnails: ${thumbs.filter((t) => t.loaded).length} images, ${thumbs.filter((t) => t.thumb === 'none').length} declared icons`)
  const modes = [['normal', 'scatter'], ['shuffle1', 'shuffle'], ['shuffle2', 'shuffle'], ['shuffle3', 'shuffle'], ['timeline', 'timeline'], ['timeline-citizen', 'filter'], ['scatter-citizen', 'untimeline']]
  for (const [mode, act] of modes) {
    if (act === 'shuffle') await page.getByRole('button', { name: 'Shuffle' }).click()
    if (act === 'timeline') await page.getByRole('button', { name: /Timeline view/ }).click()
    if (act === 'filter') await page.getByRole('button', { name: 'Becoming a citizen' }).click()
    if (act === 'untimeline') await page.getByRole('button', { name: /Scattered view/ }).click()
    await page.waitForTimeout(1500)
    await page.evaluate(() => Promise.all([...document.images].map((i) => i.decode().catch(() => {}))))
    const r = await page.evaluate(() => {
      const box = (el) => { const b = el.getBoundingClientRect(); return { left: b.left, right: b.right, top: b.top, bottom: b.bottom } }
      const cards = [...document.querySelectorAll('.mom-float')].map((e) => ({ t: e.textContent.slice(0, 30), href: e.querySelector('a')?.getAttribute('href'), ...box(e.firstElementChild) }))
      const fixed = ['.mom-head', '.mom-kinds'].map((s) => ({ t: s, ...box(document.querySelector(s)) }))
      return { cards, fixed, imgs: [...document.querySelectorAll('.mom-float img')].map((i) => i.getAttribute('src')), sw: document.documentElement.scrollWidth, root: document.querySelector('.mom-root').scrollWidth }
    })
    const probs = []
    r.cards.forEach((a, i) => {
      r.fixed.forEach((f) => hit(a, f) && probs.push(`${a.t} x ${f.t}`))
      if (a.left < -1 || a.right > w + 1) probs.push(`${a.t} off-screen`)
      r.cards.slice(i + 1).forEach((b) => hit(a, b) && probs.push(`${a.t} x ${b.t}`))
      if (!/^\/tour\.html\?inductee=[a-z-]+&chapter=[\w-]+$/.test(a.href || '')) probs.push(`${a.t}: bad href ${a.href}`)
    })
    if (!r.cards.length) probs.push('no cards')
    if (r.imgs.some((s) => LINK_ONLY.some((id) => s.includes(id)))) probs.push('link-only image shown')
    if (name === 'phone' && (r.sw > w || r.root > w)) probs.push(`horizontal scroll (${r.sw}/${r.root} > ${w})`)
    if (mode.includes('citizen') && r.cards.length < 1) probs.push('citizen filter shows nothing')
    console.log(name, mode, probs.length ? `OVERLAP/FAIL ${probs.join(' | ')}` : 'ok', `(${r.cards.length} cards)`)
    bad += probs.length
    if (shots && (mode === 'normal' || mode === 'timeline') && name !== 'laptop') await page.screenshot({ path: `${shotDir}moments-${name}-${mode}.jpg`, quality: 80 })
  }
  if (errors.length) fail(`${name}: console errors: ${errors.slice(0, 3).join(' | ')}`)
  await page.close()
}

// a moment opens its chapter
{
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.goto(`${BASE}/tour.html?view=moments`, { waitUntil: 'networkidle' })
  await page.waitForSelector('.mom-float')
  const href = await page.locator('.mom-float a').first().getAttribute('href')
  await page.locator('.mom-float a').first().click()
  await page.waitForURL(/inductee=.*chapter=/)
  const u = new URL(page.url())
  if (`${u.pathname}${u.search}` !== href) fail(`moment link opened ${u.pathname}${u.search}, not ${href}`)
  else console.log('moment opens its chapter: ok', href)
  await page.close()
}
// old links
for (const old of ['?view=constellations', '?constellation=einstein-navy-problems']) {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.goto(`${BASE}/tour.html${old}`, { waitUntil: 'networkidle' })
  const ok = (await page.locator('#mom-title').count()) === 1 && new URL(page.url()).search === '?view=moments'
  console.log(`old link ${old}:`, ok ? 'ok' : 'FAIL')
  if (!ok) fail(`old link ${old} does not land on ?view=moments`)
  await page.close()
}
// the entry points: the Einstein chapter tour HUD (desktop and phone) and the landing page
for (const [dev, opts] of [['desktop', { viewport: { width: 1440, height: 900 } }], ['phone', { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true }]]) {
  const page = await browser.newPage(opts)
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto(`${BASE}/tour.html?inductee=einstein&autostart=1`, { waitUntil: 'networkidle' })
  const btn = page.locator('[data-hud=moments]')
  if ((await btn.count()) !== 1) { fail(`${dev}: chapter tour has no Moments button`); await page.close(); continue }
  await btn.focus()
  await btn.click()
  await page.waitForSelector('.mom-float')
  const dlg = await page.evaluate(() => { const r = document.querySelector('.mom-root'); return { role: r.getAttribute('role'), modal: r.getAttribute('aria-modal'), label: document.getElementById(r.getAttribute('aria-labelledby'))?.textContent, inside: r.contains(document.activeElement) } })
  if (dlg.role !== 'dialog' || dlg.modal !== 'true' || dlg.label !== 'Moments That Made Them') fail(`${dev}: overlay is not a labelled modal dialog ${JSON.stringify(dlg)}`)
  if (!dlg.inside) fail(`${dev}: focus did not move into the overlay`)
  // Tab never leaves the overlay (forward and back)
  let escaped = false
  for (let i = 0; i < 25; i++) { await page.keyboard.press('Tab'); if (!(await page.evaluate(() => document.querySelector('.mom-root').contains(document.activeElement)))) escaped = true }
  for (let i = 0; i < 25; i++) { await page.keyboard.press('Shift+Tab'); if (!(await page.evaluate(() => document.querySelector('.mom-root').contains(document.activeElement)))) escaped = true }
  if (escaped) fail(`${dev}: Tab left the overlay`)
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  const after = await page.evaluate(() => ({ open: !!document.querySelector('.mom-root'), onOpener: document.activeElement?.getAttribute('data-hud') }))
  if (after.open) fail(`${dev}: Escape did not close the overlay`)
  else if (after.onOpener !== 'moments') fail(`${dev}: focus did not return to the Moments button`)
  else console.log(`${dev}: chapter-tour HUD opens Moments (dialog, focus in, Tab trapped), Escape closes, focus returns: ok`)
  if (errors.length) fail(`${dev}: page errors ${errors.slice(0, 2).join(' | ')}`)
  await page.close()
}
{
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await page.goto(`${BASE}/`, { waitUntil: 'networkidle' })
  const link = page.getByRole('link', { name: 'Moments That Made Them' })
  if ((await link.count()) !== 1) fail('landing has no Moments link')
  else {
    await link.click()
    await page.waitForSelector('.mom-float')
    console.log('landing link opens Moments:', new URL(page.url()).search === '?view=moments' ? 'ok' : (fail(`landing link went to ${page.url()}`), 'FAIL'))
  }
  await page.close()
}
await browser.close()
console.log(bad ? `${bad} problem(s)` : 'all ok')
process.exit(bad ? 1 : 0)
